function normalize(city: string): string {
  return city.replace(/[市区县]$/, '').trim();
}

export type CityTier = '一线城市' | '新一线城市' | '二线城市' | '三线城市' | '四线及以下城市';
export const CITY_TIER_ORDER: CityTier[] = ['一线城市', '新一线城市', '二线城市', '三线城市', '四线及以下城市'];

export function getCityTier(city: string): CityTier {
  if (!city || city === '(跳过)') return '四线及以下城市';
  const c = normalize(city);
  if (TIER_1.has(c))     return '一线城市';
  if (TIER_NEW_1.has(c)) return '新一线城市';
  if (TIER_2.has(c))     return '二线城市';
  if (TIER_3.has(c))     return '三线城市';
  return '四线及以下城市';
}
